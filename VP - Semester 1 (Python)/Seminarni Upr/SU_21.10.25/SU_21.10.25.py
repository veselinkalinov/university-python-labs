# Задача 5. Напишете програма, в която потребителя въвежда цяло число n, след това въвежда n на брой числа и намира числото с минимална стойност и числото с максимална стойност.

n = int(input("Въведете брой числа: "))
min_num = sys.maxsize
max_num = -sys.maxsize

for i in range(1, n + 1):
    num = int(input(f"Въведете число {i}: "))
    if num < min_num:
        min_num = num
    if num > max_num:
        max_num = num


print("Минималното число е:", min_num)
print("Максималното число е:", max_num)

