# Задача 1. Напишете програма, която намира произведението на числата от m до n (където n и m са въведени от потребителя), които се делят на 3 и 4. Принтирайте резултата на конзолата.

import sys
m = int(input("Въведете m: "))
n = int(input("Въведете n: "))

pr = 1

for i in range(m, n + 1):
    if i % 3 == 0 or i % 4 == 0:
        pr *= i

    print("Произведението е:", pr)


