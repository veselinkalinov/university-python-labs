# Задача 7. Програма, която въвежда стринг, който да има главни и малки букви и да отпечатваме отделно главните и малките

str = input("Въведи дума с главни и малки букви: ")
upper = ""
lower = ""

for i in str:
    if i.isupper():
        upper += i
    else:
        lower += i
print(f"Главни букви: {upper}")
print(f"Малки букви: {lower}")

# Задача 8. Програма която въвежда число n и печата равнобедрен, като върхът му е най - горе и основата му най долу и центриран, само контуриран триъгълник от звездички

n = int(input("Въведете височината на триъгълника: "))

for i in range(n):
    print(" " * (n - i - 1), end="")

    if i == 0:
        print("*")
    elif i == n - 1:
        print("*" * (2 * i + 1))
    else:
        print("*" + " " * (2 * i - 1) + "*")
