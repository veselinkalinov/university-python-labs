# Задача 3. Програма, която въвежда n цели числа и намира най - голямото между тях.


n = int(input("Въведете брой числа: "))
max = -sys.maxsize

for i in range(1, n+1):
    number = int(input(f"Въведете число номер {i}: "))
    if number > max:
        max = number
print(f"Най - голямото число от тези {n} на брой числа е {max}.")

# Задача 4. Да напишем прогарма, която въвежда n цели числа и ги сумира

n = int(input("Въведете колко на брой цели числа искате да въведете: "))
sum = 0

for i in range(1, n+1):
    num = int(input(f"Въведете число номер {i}: "))
    sum += num
print(f"Сборът на тези {n} числа е {sum}")

# Задача 5. Програма, която брои колко числа от едно до сто са кратни и на 3 и на 5

count = 0

for i in range(1, 101):
    if i % 3 == 0 and i % 5 == 0:
        count += 1
print(f"{count} на брой числа от 1 до 100 са кратни на 3 и 5")

