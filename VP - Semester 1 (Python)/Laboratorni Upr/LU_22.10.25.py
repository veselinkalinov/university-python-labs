# Задача 1. Програма, която въвежда дадена възраст и да проверим дали е непълнолетен, пълнолетен или пенсионер

import sys
age = int(input("Моята възраст е: "))
if age < 18:
    print(f"Ти си на {age}, тоест не си пълнолетен")
elif age > 18 & age < 65:
    print(f"Ти си на {age}, тоест си пълнолетен")
else:
    print(f"Ти си на {age}, тоест си пенсионер")

